#!/usr/bin/env node
// Generates the packaged app's aggregated third-party notice file.
//
// Several redistribution surfaces already carry their own notices: the staged
// Harness ships upstream's `LICENSE` and `THIRD_PARTY_NOTICES.md`, agent-browser
// ships its license text inside its resource folder, and electron-builder copies
// Electron's and Chromium's license files into the app. ND Pencil is original
// in-repo code and has no separate upstream notice. What no artifact records is
// what the application itself redistributes: the npm
// packages bundled into app.asar and the Rust crates linked into the nd-core and
// nd-browser-host binaries. This generator closes that gap and writes
// `.release/THIRD_PARTY_NOTICES.nd-dsh.md`, which release staging ships as
// `THIRD_PARTY_NOTICES.nd-dsh.md`; scripts/verify-release.mjs fails when it is
// absent or does not name every direct runtime dependency.
//
// The Rust table comes from `cargo metadata`, which needs the registry index
// that produced the release binaries. Release staging runs it directly after
// `cargo build --release`, so that cache is warm; running standalone on a cold
// cache machine can fail and names cargo's own error when it does.
import { spawnSync } from 'node:child_process'
import { existsSync, promises as fs } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const stageRoot = join(root, '.release')
const outputPath = join(stageRoot, 'THIRD_PARTY_NOTICES.nd-dsh.md')
const shippedBinaries = ['nd-core', 'nd-browser-host']

const rootManifest = await readJson(join(root, 'package.json'))
const electronManifest = await readJson(join(root, 'node_modules', 'electron', 'package.json'))
const agentBrowserManifest = await readJson(join(root, 'node_modules', 'agent-browser', 'package.json'))
const harnessPin = await readJson(join(root, 'vendor', 'deepseek-harness.json'))
const vscodeGitPin = await readJson(join(root, 'vendor', 'vscode-git.json'))
const stagedHarnessVersion = await readJson(join(stageRoot, 'harness', 'package.json'))
  .then((manifest) => manifest.version)
  .catch(() => harnessPin.lastSyncedRelease)

const npmDependencies = []
for (const name of Object.keys(rootManifest.dependencies ?? {}).sort()) {
  const directory = join(root, 'node_modules', ...name.split('/'))
  const manifest = await readJson(join(directory, 'package.json'))
  npmDependencies.push({
    name,
    version: manifest.version,
    license: declaredLicense(manifest),
    upstream: repositoryUrl(manifest.repository),
  })
}

const rustCrates = rustCrateClosure()

const lines = []
lines.push('<!-- Generated by scripts/gen-third-party-notices.mjs — do not edit by hand.')
lines.push('     Regenerate with `corepack pnpm notices:generate` (release staging runs it automatically). -->')
lines.push('')
lines.push('# ND-DSH third-party notices')
lines.push('')
lines.push(`ND-DSH is licensed under [MIT](LICENSE.nd-dsh). The distribution contains the third-party software below.`)
lines.push('Each project remains under its own license; nothing in this file changes those terms.')
lines.push('')
lines.push(`Generated from ND-DSH ${rootManifest.version} for ${process.platform}-${process.arch}.`)
lines.push('')
lines.push('## Bundled runtimes and components')
lines.push('')
lines.push('| Component | Version | License | Notice in this distribution |')
lines.push('| --- | --- | --- | --- |')
lines.push(`| DeepSeek Harness | ${stagedHarnessVersion ?? 'unstaged'} @ ${shortCommit(harnessPin.lastSyncedCommit)} | MIT | \`vendor/deepseek-harness/LICENSE\` and its generated \`THIRD_PARTY_NOTICES.md\` |`)
lines.push(`| agent-browser | ${agentBrowserManifest.version} | ${declaredLicense(agentBrowserManifest)} | \`node_modules/agent-browser/LICENSE\` |`)
lines.push(`| Source Control panel (derived from microsoft/vscode \`extensions/git\`) | @ ${shortCommit(vscodeGitPin.commit)} | ${vscodeGitPin.license} | \`vendor/vscode-git.LICENSE\` |`)
lines.push(`| Electron | ${electronManifest.version} | ${declaredLicense(electronManifest)} | \`LICENSE.electron.txt\` beside the application |`)
lines.push(`| Node.js (Harness runtime) | ${process.versions.node} | MIT and bundled third-party licenses | \`node/LICENSE\` |`)
lines.push(`| Chromium (bundled by Electron) | ${electronManifest.version} | BSD-3-Clause and others | \`LICENSES.chromium.html\` beside the application |`)
lines.push('')
lines.push('## Desktop runtime npm dependencies')
lines.push('')
lines.push(`Bundled into app.asar as declared dependencies of ND-DSH (${npmDependencies.length} direct).`)
lines.push('The complete transitive closure with exact pinned versions is recorded in `pnpm-lock.yaml`')
lines.push('(`corepack pnpm licenses list` lists it); each bundled package also keeps its own license file.')
lines.push('')
lines.push('| Package | Version | License | Upstream |')
lines.push('| --- | --- | --- | --- |')
for (const dependency of npmDependencies) {
  lines.push(`| \`${dependency.name}\` | ${dependency.version ?? 'unknown'} | ${dependency.license ?? 'see package'} | ${dependency.upstream ?? '—'} |`)
}
lines.push('')
lines.push('## Native runtime crates')
lines.push('')
lines.push(`Statically linked into the \`${shippedBinaries.join('\` and \`')}\` binaries (${rustCrates.length} crates.io packages in`)
lines.push('their non-development dependency closure). License texts are published with each crate; the')
lines.push('expressions below are taken from the crates\' own manifests via `cargo metadata`.')
lines.push('')
lines.push('| Crate | Version | License |')
lines.push('| --- | --- | --- |')
for (const crate of rustCrates) {
  lines.push(`| ${crate.name} | ${crate.version} | ${crate.license ?? 'see crate repository'} |`)
}
lines.push('')

await fs.mkdir(stageRoot, { recursive: true })
await fs.writeFile(outputPath, `${lines.join('\n')}`, 'utf8')
console.log(`Third-party notices written: ${outputPath}`)
console.log(`Desktop npm dependencies: ${npmDependencies.length}; native runtime crates: ${rustCrates.length}.`)

/**
 * Walk the resolve graph from the two shipped binaries and keep only the
 * crates.io packages they link, skipping dev-only edges so the notice list
 * describes the artifact rather than the development workspace.
 */
function rustCrateClosure() {
  const metadata = cargoMetadata()
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]))
  const roots = metadata.packages
    .filter((entry) => shippedBinaries.includes(entry.name) && entry.source === null)
    .map((entry) => entry.id)
  const reached = new Set()
  const queue = [...roots]
  while (queue.length > 0) {
    const id = queue.pop()
    if (reached.has(id)) continue
    reached.add(id)
    for (const dependency of nodes.get(id)?.deps ?? []) {
      if (dependency.dep_kinds.every((kind) => kind.kind === 'dev')) continue
      queue.push(dependency.pkg)
    }
  }
  return metadata.packages
    .filter((entry) => reached.has(entry.id) && entry.source !== null)
    .map((entry) => ({ name: entry.name, version: entry.version, license: entry.license }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
}

function cargoMetadata() {
  const cargo = process.platform === 'win32' ? 'cargo.exe' : 'cargo'
  const result = spawnSync(cargo, ['metadata', '--format-version', '1', '--locked'], {
    cwd: root,
    encoding: 'utf8',
    windowsHide: true,
    env: process.env,
    maxBuffer: 256 * 1024 * 1024,
  })
  if (result.error) throw result.error
  if (result.status !== 0) {
    throw new Error(
      `cargo metadata failed, so the native runtime crate notices cannot be generated. It needs the registry ` +
      `index that produced the release binaries.\n${(result.stderr ?? '').trim()}`,
    )
  }
  return JSON.parse(result.stdout)
}

/** Modern `license`, or the legacy `licenses` array some packages still declare. */
function declaredLicense(manifest) {
  if (typeof manifest.license === 'string' && manifest.license.length > 0) return manifest.license
  const legacy = Array.isArray(manifest.licenses) ? manifest.licenses : []
  const types = legacy.map((entry) => entry?.type).filter((type) => typeof type === 'string')
  return types.length > 0 ? types.join(' OR ') : undefined
}

function repositoryUrl(repository) {
  const url = typeof repository === 'string' ? repository : repository?.url
  if (typeof url !== 'string') return undefined
  return url.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '')
}

function shortCommit(commit) {
  return typeof commit === 'string' ? commit.slice(0, 12) : 'unpinned'
}

async function readJson(path) {
  return JSON.parse(await fs.readFile(path, 'utf8'))
}

if (!existsSync(outputPath)) throw new Error(`Third-party notices were not written: ${outputPath}`)
